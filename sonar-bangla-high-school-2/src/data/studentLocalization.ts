export const formatClassLevel = (classLevel: string, isBn: boolean): string => {
  if (!isBn) {
    if (classLevel.toLowerCase().includes('pred 1') || classLevel.toLowerCase().includes('prep 1')) return 'Pred 1';
    if (classLevel.toLowerCase().includes('pred 2') || classLevel.toLowerCase().includes('prep 2')) return 'Pred 2';
    if (classLevel.includes('Class')) {
      const num = classLevel.replace('Class', '').trim();
      return `Class ${num}`;
    }
    return classLevel;
  }

  const norm = classLevel.toLowerCase();
  if (norm.includes('10')) return '১০ম শ্রেণি';
  if (norm.includes('9')) return '৯ম শ্রেণি';
  if (norm.includes('8')) return '৮ম শ্রেণি';
  if (norm.includes('7')) return '৭ম শ্রেণি';
  if (norm.includes('6')) return '৬ষ্ঠ শ্রেণি';
  if (norm.includes('5')) return '৫ম শ্রেণি';
  if (norm.includes('4')) return '৪র্থ শ্রেণি';
  if (norm.includes('3')) return '৩য় শ্রেণি';
  if (norm.includes('2') && !norm.includes('pred') && !norm.includes('prep')) return '২য় শ্রেণি';
  if (norm.includes('1') && !norm.includes('pred') && !norm.includes('prep')) return '১ম শ্রেণি';
  if (norm.includes('pred 1') || norm.includes('prep 1')) return 'প্রেপ ১';
  if (norm.includes('pred 2') || norm.includes('prep 2')) return 'প্রেপ ২';
  if (norm.includes('all')) return 'সকল শ্রেণি';
  return classLevel;
};

export const formatGroup = (group: string, isBn: boolean): string => {
  if (!isBn) return group;
  switch (group) {
    case 'Science':
      return 'বিজ্ঞান';
    case 'Business Studies':
      return 'ব্যবসায় শিক্ষা';
    case 'Humanities':
      return 'মানবিক';
    case 'General':
      return 'সাধারণ';
    case 'All Groups':
      return 'সকল গ্রুপ';
    default:
      return group;
  }
};

export const formatSection = (section: string, isBn: boolean, short: boolean = false): string => {
  if (!isBn) {
    if (short) return section.replace('Section ', '');
    return section;
  }
  const norm = section.toLowerCase();
  if (norm.includes('section a') || norm.trim() === 'a') {
    return short ? 'ক (A)' : 'শাখা এ (A)';
  }
  if (norm.includes('section b') || norm.trim() === 'b') {
    return short ? 'খ (B)' : 'শাখা বি (B)';
  }
  if (norm.includes('section c') || norm.trim() === 'c') {
    return short ? 'গ (C)' : 'শাখা সি (C)';
  }
  if (norm.includes('all')) {
    return 'সকল শাখা';
  }
  return section;
};
